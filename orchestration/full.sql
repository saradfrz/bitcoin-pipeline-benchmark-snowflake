USE DATABASE BTC_TRADING;
USE SCHEMA ORCHESTRATION;

ALTER TASK IF EXISTS BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_FULL SUSPEND;
ALTER TASK IF EXISTS BTC_TRADING.ORCHESTRATION.FULL_DAILY_SUMMARY_AND_GOLD SUSPEND;

-- Validate stage coverage before resetting pipeline tables.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_FULL
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
AS
EXECUTE IMMEDIATE FROM @BTC_TRADING.ORCHESTRATION.DI_PIPE_ENG_REPO/branches/main/snowflake/quality/dq_landing_full.sql;

CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_RESET_AFTER_LANDING_CHECK
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_FULL
AS
BEGIN
    TRUNCATE TABLE BTC_TRADING.BINANCE_BRONZE.BTCUSDT_TRADES_BRONZE;

    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_SILVER.BTCUSDT_TRADES;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_SILVER.BTCUSDT_DAILY_TRADE_SUMMARY;

    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.INT_BTCUSDT_SMA_50D_DAILY_INPUT;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.INT_BTCUSDT_SMA_50D_ROLLING_MEAN;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.MART_BTCUSDT_SMA_50D;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.INT_BTCUSDT_SMA_200D_DAILY_INPUT;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.INT_BTCUSDT_SMA_200D_ROLLING_MEAN;
    TRUNCATE TABLE IF EXISTS BTC_TRADING.BINANCE_GOLD.MART_BTCUSDT_SMA_200D;

END;

-- Child 1. Reload all matching BTCUSDT Parquet files from LANDING_ZONE.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_BRONZE_BTCUSDT_TRADES_RAW
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_RESET_AFTER_LANDING_CHECK
AS
    EXECUTE IMMEDIATE FROM
        @BTC_TRADING.ORCHESTRATION.ETL_SCRIPTS/bronze_btcusdt_trades_raw.sql
        USING (force_reload => TRUE);

-- Child 2. Populate the empty Silver trades table from the reloaded Bronze table.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_TRADES
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_BRONZE_BTCUSDT_TRADES_RAW
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select +silver_btcusdt_trades';

-- Child 3. Aggregate Silver trades into one row per BTCUSDT trading day.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_TRADES
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select silver_btcusdt_daily_trade_summary';

CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY
AS
CALL BTC_TRADING.ORCHESTRATION.DQ_AFTER_SUMMARY(
    SYSTEM$GET_PREDECESSOR_RETURN_VALUE('BINANCE_BITCOIN_FULL')
);

-- Child 04. Compute MM50 from daily Silver closes.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_SMA_50D
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_sma_50d --full-refresh';

-- Child 05. Compute MM200 from daily Silver closes.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_SMA_200D
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_sma_200d --full-refresh';

-- Child 07. Compute continuous daily BTC CVD.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_CVD
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_cvd --full-refresh';

-- Child 08. Compute daily volume-weighted price in USDT per BTC.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_VWAP
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_vwap --full-refresh';



ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_VWAP RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_CVD RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_SMA_200D RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_GOLD_MART_BTCUSDT_SMA_50D RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_SILVER_BTCUSDT_TRADES RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_BRONZE_BTCUSDT_TRADES_RAW RESUME;

ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_RESET_AFTER_LANDING_CHECK RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.FULL_DQ_AFTER_SUMMARY RESUME;
