USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE BTC_TRADING;

-- 01. Bronze: raw trades
SELECT *
FROM BINANCE_BRONZE.BTCUSDT_TRADES_BRONZE
ORDER BY TRY_TO_NUMBER(trade_time_us), TRY_TO_NUMBER(trade_id)
LIMIT 10;

-- 02. Silver: normalized trades
SELECT *
FROM BINANCE_SILVER.BTCUSDT_TRADES
ORDER BY trade_timestamp_utc, trade_id
LIMIT 10;

-- 03. Silver: daily summary
SELECT *
FROM BINANCE_SILVER.BTCUSDT_DAILY_TRADE_SUMMARY
ORDER BY data DESC, symbol
LIMIT 10;

-- 04. Gold: SMA 50 days
SELECT *
FROM BINANCE_GOLD.MART_BTCUSDT_SMA_50D
WHERE SMA_50D is not null
ORDER BY data DESC, symbol
LIMIT 10;

-- 05. Gold: SMA 200 days
SELECT *
FROM BINANCE_GOLD.MART_BTCUSDT_SMA_200D
WHERE SMA_200D is not null
ORDER BY data DESC, symbol
LIMIT 10;

-- 06. Gold: CVD
SELECT *
FROM BINANCE_GOLD.MART_BTCUSDT_CVD
ORDER BY data, symbol
LIMIT 10;

-- 07. Gold: VWAP
SELECT *
FROM BINANCE_GOLD.MART_BTCUSDT_VWAP
ORDER BY data, symbol
LIMIT 10;

-- 08. Row counts for all pipeline tables
SELECT 'BINANCE_BRONZE.BTCUSDT_TRADES_BRONZE' AS table_name,
       COUNT(*) AS total_rows
FROM BINANCE_BRONZE.BTCUSDT_TRADES_BRONZE

UNION ALL
SELECT 'BINANCE_SILVER.BTCUSDT_TRADES', COUNT(*)
FROM BINANCE_SILVER.BTCUSDT_TRADES

UNION ALL
SELECT 'BINANCE_SILVER.BTCUSDT_DAILY_TRADE_SUMMARY', COUNT(*)
FROM BINANCE_SILVER.BTCUSDT_DAILY_TRADE_SUMMARY

UNION ALL
SELECT 'BINANCE_GOLD.MART_BTCUSDT_SMA_50D', COUNT(*)
FROM BINANCE_GOLD.MART_BTCUSDT_SMA_50D

UNION ALL
SELECT 'BINANCE_GOLD.MART_BTCUSDT_SMA_200D', COUNT(*)
FROM BINANCE_GOLD.MART_BTCUSDT_SMA_200D

UNION ALL
SELECT 'BINANCE_GOLD.MART_BTCUSDT_CVD', COUNT(*)
FROM BINANCE_GOLD.MART_BTCUSDT_CVD

UNION ALL
SELECT 'BINANCE_GOLD.MART_BTCUSDT_VWAP', COUNT(*)
FROM BINANCE_GOLD.MART_BTCUSDT_VWAP



--ORDER BY table_name;