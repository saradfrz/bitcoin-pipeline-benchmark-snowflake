USE DATABASE BTC_TRADING;
USE SCHEMA BTC_TRADING.ORCHESTRATION;

-- Manual entry point. The children do the loading.
ALTER TASK IF EXISTS BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_DELTA SUSPEND;

-- Keep the previously proposed Gold step inactive if it exists.
ALTER TASK IF EXISTS BTC_TRADING.ORCHESTRATION.DELTA_DAILY_SUMMARY_AND_GOLD SUSPEND;

CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_DELTA
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
AS
EXECUTE IMMEDIATE FROM @BTC_TRADING.ORCHESTRATION.DI_PIPE_ENG_REPO/branches/main/snowflake/quality/dq_landing_delta.sql;

-- Child 1. Load new landing-zone files into Bronze.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_BRONZE_BTCUSDT_TRADES_RAW
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.BINANCE_BITCOIN_DELTA
AS
    EXECUTE IMMEDIATE FROM
        @BTC_TRADING.ORCHESTRATION.ETL_SCRIPTS/bronze_btcusdt_trades_raw.sql
        USING (force_reload => FALSE);

-- Child 2. Build Silver trades after Bronze succeeds.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_TRADES
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_BRONZE_BTCUSDT_TRADES_RAW
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select +silver_btcusdt_trades';


-- Child 3. Aggregate Silver trades into one row per BTCUSDT trading day.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_TRADES
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select silver_btcusdt_daily_trade_summary';

CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY
AS
CALL BTC_TRADING.ORCHESTRATION.DQ_AFTER_SUMMARY(
    SYSTEM$GET_PREDECESSOR_RETURN_VALUE('BINANCE_BITCOIN_DELTA')
);

-- Child 04. Compute MM50 from daily Silver closes.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_50D
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_sma_50d';

-- Child 05. Compute MM200 from daily Silver closes.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_200D
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_sma_200d';

-- Child 07. Compute continuous daily BTC CVD.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_CVD
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_cvd';

-- Child 08. Compute daily volume-weighted price in USDT per BTC.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_VWAP
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY
AS
    EXECUTE DBT PROJECT BTC_TRADING.ORCHESTRATION.BINANCE
        ARGS = 'build --select gold_mart_btcusdt_vwap';



-- Retention runs only after every Gold branch succeeds, never as a finalizer.
CREATE OR REPLACE TASK BTC_TRADING.ORCHESTRATION.DELTA_PRUNE_366_DAYS
    WAREHOUSE = SNOWFLAKE_LEARNING_WH
    USER_TASK_TIMEOUT_MS = 14400000
    AFTER BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_50D,
          BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_200D,
          BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_CVD,
          BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_VWAP
AS
    EXECUTE IMMEDIATE FROM
        @BTC_TRADING.ORCHESTRATION.DI_PIPE_ENG_REPO/branches/main/snowflake/maintenance/prune_366_days.sql;

ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_PRUNE_366_DAYS RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_VWAP RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_CVD RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_200D RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_GOLD_MART_BTCUSDT_SMA_50D RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_DAILY_TRADE_SUMMARY RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_SILVER_BTCUSDT_TRADES RESUME;
ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_BRONZE_BTCUSDT_TRADES_RAW RESUME;

ALTER TASK BTC_TRADING.ORCHESTRATION.DELTA_DQ_AFTER_SUMMARY RESUME;
